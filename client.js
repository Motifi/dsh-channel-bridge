    function bridgeError(kind, status, code) {
      const error = new Error(kind);
      error.bridgeKind = kind;
      error.httpStatus = status || 0;
      error.bridgeCode = code || '';
      return error;
    }

    // Never display upstream messages, QR URLs, or raw exception text. Only local copy reaches the UI.
    function errorKey(error) {
      const status = error && error.httpStatus;
      const code = String(error && error.bridgeCode || '').toUpperCase().replace(/[-.]/g, '_');
      if (status === 401 || code === 'UNAUTHORIZED') return 'errors.unauthorized';
      if (status === 403 || code === 'FORBIDDEN' || code === 'OWNER_REQUIRED') return 'errors.forbidden';
      const codes = {
        PAIRING_CODE_INVALID: 'errors.invalidPairing', PAIRING_CODE_EXPIRED: 'errors.pairingExpired',
        ALREADY_APPROVED: 'errors.approvalConflict', LOGIN_EXPIRED: 'errors.loginExpired',
        LOGIN_VERIFY_REQUIRED: 'login.verify-code', LOGIN_VERIFY_FAILED: 'errors.verificationFailed',
        NOT_CONNECTED: 'disabled.noAccount', AUTH_REQUIRED: 'status.auth-required',
        MODEL_UNAVAILABLE: 'errors.model', NETWORK_ERROR: 'errors.network',
        BUSY: 'errors.conflict', STORAGE_ERROR: 'errors.server', INTERNAL_ERROR: 'errors.server',
      };
      if (codes[code]) return codes[code];
      if (status === 404) return 'errors.hostUnavailable';
      if (status === 409) return 'errors.conflict';
      if (status === 429) return 'errors.rateLimited';
      if (status >= 500) return 'errors.server';
      if (error && error.bridgeKind === 'network') return 'errors.network';
      if (error && error.bridgeKind === 'timeout') return 'errors.timeout';
      if (error && error.bridgeKind === 'response') return 'errors.invalidResponse';
      return 'errors.failed';
    }

    function createOwnerApi(fetchImpl, path, header, validate) {
      return async function request(action, payload, signal) {
        let response;
        try {
          response = await fetchImpl(path, {
            method: 'POST', credentials: 'same-origin', cache: 'no-store',
            headers: { 'Content-Type': 'application/json', [header]: '1' },
            body: JSON.stringify({ ...payload, action }), signal,
          });
        } catch (error) {
          if (signal.aborted) throw error;
          throw bridgeError('network');
        }
        let body;
        try { body = await response.json(); } catch (_) {
          throw bridgeError('response', response.status);
        }
        if (!response.ok || !body || body.ok !== true) {
          throw bridgeError('host', response.status,
            body && body.error && typeof body.error.code === 'string' ? body.error.code : '');
        }
        if (!validate(body.value)) throw bridgeError('response', response.status);
        return body.value;
      };
    }

