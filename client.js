    function writeChannelField(config, name, value) {
      const segments = name.split('.');
      if (segments.some(part => !/^[A-Za-z][A-Za-z0-9_-]*$/.test(part)
        || part === 'constructor' || part === 'prototype')) throw new TypeError('field');
      const key = segments.pop();
      let parent = config;
      for (const part of segments) {
        if (!Object.hasOwn(parent, part)) parent[part] = {};
        if (!parent[part] || typeof parent[part] !== 'object' || Array.isArray(parent[part])) {
          throw new TypeError('field');
        }
        parent = parent[part];
      }
      if (Object.hasOwn(parent, key)) throw new TypeError('field');
      parent[key] = value;
    }

    function parseChannelConfig(fields, values) {
      const config = {};
      for (const { field, kind, required, choices } of fields) {
        const input = String(Object.hasOwn(values, field) ? values[field] : '').trim();
        if (!input) {
          if (required) throw new TypeError('required');
          continue;
        }
        let value = input;
        if (kind === 'bool') {
          if (input !== 'true' && input !== 'false') throw new TypeError('boolean');
          value = input === 'true';
        } else if (kind === 'int' || kind === 'float') {
          value = Number(input);
          if (!Number.isFinite(value) || (kind === 'int' && !Number.isSafeInteger(value))) {
            throw new TypeError('number');
          }
        } else if (kind === 'list') {
          value = input.split(/[\n,]/).map(item => item.trim()).filter(Boolean);
        } else if (kind === 'json') {
          value = JSON.parse(input);
        } else if (kind === 'enum' && !choices?.includes(input)) {
          throw new TypeError('choice');
        }
        writeChannelField(config, field, value);
      }
      return config;
    }

    function createController(api, options) {
      // Window timer methods require their owning global as `this`. Storing the
      // bare methods here makes clock.setTimeout()/clearTimeout() throw in browsers.
      const clock = options && options.clock || {
        now: () => Date.now(),
        setTimeout: (callback, ms) => globalThis.setTimeout(callback, ms),
        clearTimeout: handle => globalThis.clearTimeout(handle),
      };
      let state = Object.freeze({
        snapshot: null, busy: null, refreshing: false, initialLoading: true,
        online: !(options && options.online === false), permission: null,
        transportError: null, actionError: null, notice: null, uncertain: false,
      });
      const listeners = new Set();
      let running = false;
      let active = null;
      let pollTimer = null;
      let sequence = 0;
      let failures = 0;
      function patch(update) {
        state = Object.freeze({ ...state, ...update });
        for (const listener of listeners) listener();
      }
      function clearPoll() {
        if (pollTimer !== null) clock.clearTimeout(pollTimer);
        pollTimer = null;
      }
      function schedule() {
        clearPoll();
        if (!running || !state.online || active) return;
        const base = liveLogin(state.snapshot, clock.now()) ? 2_000 : 3_000;
        const delay = failures ? Math.min(15_000, base * (2 ** Math.min(failures, 3))) : base;
        pollTimer = clock.setTimeout(() => {
          pollTimer = null;
          void perform('status', {});
        }, delay);
      }
      async function perform(action, payload, busyKey) {
        if (!running || !state.online) return false;
        if (active) {
          if (action === 'status' || active.action !== 'status') return false;
          // A manual mutation supersedes the older status read. A late response cannot commit.
          clock.clearTimeout(active.timeout);
          active.controller.abort();
        }
        clearPoll();
        const request = { id: ++sequence, action, controller: new AbortController(), timedOut: false, offlineAbort: false, timeout: null };
        active = request;
        let rejectInterrupted;
        const interrupted = new Promise((_resolve, reject) => { rejectInterrupted = reject; });
        const onAbort = () => rejectInterrupted(bridgeError(request.timedOut ? 'timeout' : 'network'));
        request.controller.signal.addEventListener('abort', onAbort, { once: true });
        try {
          patch(action === 'status'
            ? { refreshing: true }
            : { busy: busyKey || action, refreshing: false, actionError: null, notice: null });
          request.timeout = clock.setTimeout(() => {
            if (active === request) {
              request.timedOut = true;
              request.controller.abort();
            }
          }, action === 'status' ? 15_000 : 30_000);
          // A deadline must settle the UI even if a transport or JSON body reader
          // ignores AbortSignal. The old request still cannot commit a late result.
          const snapshot = await Promise.race([api(action, payload, request.controller.signal), interrupted]);
          if (!running || active !== request) return false;
          if (request.controller.signal.aborted) throw bridgeError(request.timedOut ? 'timeout' : 'network');
          failures = 0;
          patch({
            snapshot, initialLoading: false, permission: null, transportError: null, uncertain: false,
            ...(action === 'status' ? {} : { actionError: null, notice: NOTICE_KEYS[action] || null }),
          });
          return true;
        } catch (error) {
          if (!running || active !== request) return false;
          const key = request.timedOut ? 'errors.timeout' : !state.online ? 'errors.offline'
            : request.offlineAbort ? 'errors.network' : errorKey(error);
          const failure = { key, action, userId: payload.userId || null };
          if (payload.id) failure.channelId = payload.id;
          if (action === 'status') failures += 1;
          patch({
            initialLoading: false,
            ...(action === 'status' ? { transportError: failure } : { actionError: failure }),
            ...(['errors.unauthorized', 'errors.forbidden'].includes(key) ? { permission: key } : {}),
            ...(action !== 'status' && ['errors.offline', 'errors.network', 'errors.timeout', 'errors.invalidResponse', 'errors.server'].includes(key)
              ? { uncertain: true } : {}),
          });
          return false;
        } finally {
          request.controller.signal.removeEventListener('abort', onAbort);
          if (request.timeout !== null) clock.clearTimeout(request.timeout);
          if (active === request) {
            active = null;
            patch({ busy: null, refreshing: false });
            schedule();
          }
        }
      }
      return {
        getSnapshot: () => state,
        subscribe(listener) { listeners.add(listener); return () => { listeners.delete(listener); }; },
        start() { if (running) return; running = true; return perform('status', {}); },
        stop() {
          running = false;
          sequence += 1;
          clearPoll();
          if (active) { clock.clearTimeout(active.timeout); active.controller.abort(); }
          active = null;
          patch({ busy: null, refreshing: false });
        },
        refresh: () => perform('status', {}),
        run(action, payload, busyKey) {
          if (!MUTATIONS.has(action) || !state.snapshot || state.permission || state.transportError || state.uncertain) {
            return Promise.resolve(false);
          }
          return perform(action, payload || {}, busyKey);
        },
        setOnline(online) {
          if (state.online === online) return;
          patch({ online });
          if (!online) {
            clearPoll();
            if (active) { active.offlineAbort = true; active.controller.abort(); }
          }
          else if (running && !active) void perform('status', {});
        },
      };
    }
