    function safeQrSource(value) {
      return typeof value === 'string' && value.length < 2_000_000
        && /^data:image\/(?:png|jpeg|webp|gif);base64,[A-Za-z0-9+/]+={0,2}$/.test(value);
    }

    function liveLogin(snapshot, now) {
      const login = snapshot && snapshot.login;
      return Boolean(login && ACTIVE_LOGIN_STATES.has(login.status)
        && Number.isFinite(login.expiresAt) && login.expiresAt > now);
    }

    function deriveLoginView(snapshot, now, brokenQrId) {
      const login = snapshot && snapshot.login;
      const active = liveLogin(snapshot, now);
      const expired = Boolean(login && (login.status === 'expired'
        || (ACTIVE_LOGIN_STATES.has(login.status) && !active)));
      // A retained account identifies the previous sign-in, not a completed new attempt.
      // Pending (and unsuccessful) login state must stay visible until success or cancellation.
      const incompleteLogin = Boolean(login && login.status !== 'succeeded');
      const signedIn = Boolean(snapshot && snapshot.account && !incompleteLogin
        && !['auth-required', 'error', 'disconnected'].includes(snapshot.connectionStatus));
      return {
        active, expired, signedIn,
        showLogin: Boolean(login && !signedIn),
        showQr: Boolean(active && safeQrSource(login.qrDataUrl) && brokenQrId !== login.id),
        needsVerification: Boolean(active && (login.status === 'verify-code' || login.verificationFailed)),
        showCancel: active,
        showStart: !signedIn,
      };
    }

