    function useBridgeController(apiFactory) {
      const store = React.useMemo(() => createController(apiFactory((...args) => window.fetch(...args)), {
        online: typeof navigator === 'undefined' || navigator.onLine !== false,
      }), [apiFactory]);
      const state = React.useSyncExternalStore(store.subscribe, store.getSnapshot, store.getSnapshot);
      React.useEffect(() => {
        const online = () => { store.setOnline(true); };
        const offline = () => { store.setOnline(false); };
        window.addEventListener('online', online);
        window.addEventListener('offline', offline);
        void store.start();
        return () => {
          window.removeEventListener('online', online);
          window.removeEventListener('offline', offline);
          store.stop();
        };
      }, [store]);
      return [store, state];
    }

    function ConfirmControl({ t, action, busyKey, state, reason, titleKey, bodyKey, buttonKey, confirmKey, payload, store, onConfirmed }) {
      const [confirming, setConfirming] = React.useState(false);
      const trigger = React.useRef(null);
      const cancel = React.useRef(null);
      const titleId = React.useId();
      const bodyId = React.useId();
      const restoreTriggerOnCancel = React.useRef(false);
      React.useEffect(() => {
        if (confirming) cancel.current?.focus();
        else if (restoreTriggerOnCancel.current) {
          restoreTriggerOnCancel.current = false;
          trigger.current?.focus();
        }
      }, [confirming]);
      function dismiss() { restoreTriggerOnCancel.current = true; setConfirming(false); }
      if (!confirming) return h(ActionButton, {
        label: t(buttonKey), reason, onClick: () => { setConfirming(true); },
        variant: 'danger', buttonRef: trigger,
      });
      return h('div', {
        className: 'wxb-confirm', role: 'group', 'aria-labelledby': titleId, 'aria-describedby': bodyId,
        onKeyDown: event => {
          if (event.key === 'Escape' && !state.busy) { event.preventDefault(); event.stopPropagation(); dismiss(); }
        },
      },
      h('p', { id: titleId }, t(titleKey)),
      h('p', { id: bodyId, className: 'wxb-muted' }, t(bodyKey)),
      h('div', { className: 'wxb-actions' },
        h(ActionButton, { label: t('confirm.cancel'), onClick: dismiss, buttonRef: cancel,
          reason: state.busy ? t('disabled.busy') : null }),
        h(ActionButton, { label: t(confirmKey), variant: 'danger', reason,
          busy: state.busy === busyKey, busyLabel: t(`busy.${action}`),
          onClick: async () => {
            if (await store.run(action, payload, busyKey)) {
              // The mutation may already have unmounted this control. Its stable parent owns success focus.
              restoreTriggerOnCancel.current = false;
              onConfirmed?.();
              setConfirming(false);
            }
          } })));
    }

    function SessionCopy({ t, sessionId, openSession }) {
      const [copy, setCopy] = React.useState('idle');
      const mounted = React.useRef(true);
      React.useEffect(() => { mounted.current = true; return () => { mounted.current = false; }; }, []);
      return h('div', { className: 'wxb-stack' },
        h('span', { className: 'wxb-muted' }, t('users.sessionLabel')),
        h('code', { className: 'wxb-session', tabIndex: 0, 'aria-label': t('users.sessionLabel') }, sessionId),
        h('div', { className: 'wxb-actions' }, openSession ? h(ActionButton, {
          label: t('features.openSession'), onClick: () => openSession(sessionId),
        }) : null, h(ActionButton, {
          label: t('actions.copy'), busy: copy === 'busy', busyLabel: t('busy.copy'),
          reason: copy === 'busy' ? t('busy.copy') : null,
          onClick: async () => {
            if (copy === 'busy') return;
            setCopy('busy');
            try {
              if (!navigator.clipboard || typeof navigator.clipboard.writeText !== 'function') throw new Error('clipboard');
              await navigator.clipboard.writeText(sessionId);
              if (mounted.current) setCopy('done');
            } catch (_) { if (mounted.current) setCopy('error'); }
          },
        })),
        h('p', { role: copy === 'error' ? 'alert' : 'status', 'aria-live': 'polite',
          className: copy === 'error' ? 'wxb-error' : 'wxb-muted' },
        copy === 'error' ? t('errors.clipboard') : copy === 'done' ? t('actions.copied') : null));
    }

